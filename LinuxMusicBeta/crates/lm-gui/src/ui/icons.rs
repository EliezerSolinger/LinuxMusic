static IMAGES: LazyLock<HashMap<&'static str, Arc<Image>>> = LazyLock::new(|| {
    ICONS.iter().map(|(name, fmt, bytes)| (*name, Arc::new(Image::from_bytes(*fmt, bytes.to_vec())))).collect()
});

/// Whether the legacy has an icon by this name
#[cfg_attr(not(test), expect(dead_code, reason = "the tests check the names the screens use"))]
pub fn has_icon(name: &str) -> bool {
    IMAGES.contains_key(name)
}

/// A legacy icon at its usual toolbar size (16 px); `.size(...)` changes it. An unknown name draws nothing (and the
/// test lists the names the screens use)
pub fn icon(name: &str) -> Img {
    match IMAGES.get(name) {
        Some(image) => img(image.clone()).size(px(16.)).flex_none(),
        None => img(Arc::new(Image::from_bytes(ImageFormat::Png, Vec::new()))).size(px(0.)),
    }
}

