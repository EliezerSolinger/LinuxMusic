/// The index of a key in the table
pub fn chord_index(key: &str) -> Option<usize> {
    CHORD_KEYS.iter().position(|k| *k == key)
}

/// The intervals of the entry with this key
pub fn chord(key: &str) -> Option<&'static [u8]> {
    chord_index(key).map(|i| CHORD_INTERVALS[i])
}

/// Whether an entry is a scale rather than a chord (the piano roll lists them apart)
pub fn is_scale(key: &str) -> bool {
    key.starts_with("scale-")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_whole_and_unique() {
        for (i, k) in CHORD_KEYS.iter().enumerate() {
            assert!(!CHORD_KEYS[..i].contains(k), "{k} twice");
            let intervals = CHORD_INTERVALS[i];
            assert_eq!(intervals[0], 0, "{k} starts at its root");
            assert!(intervals.windows(2).all(|w| w[0] < w[1]), "{k} ascends");
        }
        assert_eq!(chord("maj7"), Some(&[0u8, 4, 7, 11][..]));
        assert_eq!(chord("scale-persian"), Some(&[0u8, 1, 4, 5, 6, 8, 11][..]));
        assert!(is_scale("scale-blues") && !is_scale("5"));
    }
}
